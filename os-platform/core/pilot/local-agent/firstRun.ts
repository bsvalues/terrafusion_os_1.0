import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';

import { appendLocalAgentEvent, terrafusionPath } from './eventLog.js';

export interface LocalAgentEnvCheck {
  name: string;
  ok: boolean;
  detail: string;
}

export interface LocalAgentInitReport {
  createdAt: number;
  repoRoot: string;
  envChecks: LocalAgentEnvCheck[];
  cardCreated: boolean;
  cardPath: string;
  cardAlreadyExisted: boolean;
  nextCommands: string[];
  blockers: string[];
}

