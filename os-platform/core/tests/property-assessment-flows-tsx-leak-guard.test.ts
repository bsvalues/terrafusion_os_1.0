import fs from "node:fs";
import path from "node:path";
import { assertNoRawColorLeaks } from "../../../frontend/apps/os-shell/src/tools/ui-tokens/leak-guard";

/**
 * Leak guard for PropertyAssessmentFlows.tsx (Phase 177).
 * Typical regressions: hover shadow rgba emerald glow on flow buttons.
 */
describe("PropertyAssessmentFlows.tsx leak guard", () => {
  it("contains no raw color values", () => {
    const filePath = path.resolve(
      __dirname, "..", "..", "..",
      "frontend/apps/os-shell/src/features/gpt/components/PropertyAssessmentFlows.tsx",
    );
    expect(
      fs.existsSync(filePath),
      `Expected file to exist: ${filePath}`,
    ).toBe(true);
    const content = fs.readFileSync(filePath, "utf8");
    assertNoRawColorLeaks(content, { label: "PropertyAssessmentFlows.tsx" });
  });
});
