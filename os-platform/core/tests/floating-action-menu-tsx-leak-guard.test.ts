import fs from 'node:fs';
import path from 'node:path';
import { assertNoRawColorLeaks } from '../../../tools/ui-tokens/leak-guard';

/**
 * Leak guard for FloatingActionMenu.tsx (Phase 116).
 * MUI styled() boxShadow/border/bg cyan alphas + neutral overlays.
 */
describe('FloatingActionMenu.tsx leak guard', () => {
  it('contains no raw color values', () => {
    const filePath = path.join(
      process.cwd(),
      'frontend/apps/os-shell/src/components/common/FloatingActionMenu.tsx'
    );
    expect(fs.existsSync(filePath), `Expected file to exist: ${filePath}`).toBe(true);
    const content = fs.readFileSync(filePath, 'utf8');
    assertNoRawColorLeaks(content, { label: 'FloatingActionMenu.tsx' });
  });
});
