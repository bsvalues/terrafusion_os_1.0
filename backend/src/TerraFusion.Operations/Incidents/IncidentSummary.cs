namespace TerraFusion.Operations.Incidents;

/// <summary>
/// The main incident summary produced by triage.
/// Contains classified incident with correlated alerts, metrics, and recommendations.
/// </summary>
/// <remarks>
/// This DTO is designed for:
/// - County IT staff (clear title, description, actionable recommendations)
/// - On-call engineers (correlated alerts, metrics, trace IDs)
/// - CIO/CTO incident reviews (severity, impact scope, audit trail)
///
/// IMMUTABILITY RULE (for LLM integration):
/// - incidentId, severity, impactedCountyIds, alerts, metrics MUST NOT be changed by LLM
/// - title, description, recommendations MAY be refined by LLM
/// </remarks>
public record IncidentSummary
{
    /// <summary>
    /// Unique identifier for this incident.
    /// Generated by the triage engine, immutable after creation.
    /// </summary>
    public required Guid IncidentId { get; init; }

    /// <summary>
    /// Overall severity of the incident.
    /// Determined by the highest severity alert and escalation rules.
    /// IMMUTABLE - LLM must not change this value.
    /// </summary>
    public required IncidentSeverity OverallSeverity { get; init; }

    /// <summary>
    /// Current lifecycle status of the incident.
    /// </summary>
    public required IncidentStatus Status { get; init; }

    /// <summary>
    /// Primary county affected by this incident.
    /// Null if incident affects infrastructure (not county-specific).
    /// IMMUTABLE - LLM must not change this value.
    /// </summary>
    public Guid? PrimaryCountyId { get; init; }

    /// <summary>
    /// All counties affected by this incident.
    /// May include multiple counties for infrastructure issues.
    /// IMMUTABLE - LLM must not change this value.
    /// </summary>
    public required List<Guid> ImpactedCountyIds { get; init; }

    /// <summary>
    /// Short, human-readable title for the incident.
    /// Should be understandable at a glance.
    /// MAY be refined by LLM for clarity.
    /// </summary>
    /// <example>
    /// "Atlas Forecast Orchestrator Stall - Benton County"
    /// </example>
    public required string Title { get; init; }

    /// <summary>
    /// Detailed description of what happened and the impact.
    /// Should explain the incident in terms county IT staff can understand.
    /// MAY be expanded by LLM with additional explanation.
    /// </summary>
    public required string Description { get; init; }

    /// <summary>
    /// List of alerts that contributed to this incident.
    /// Grouped by the triage engine's correlation logic.
    /// IMMUTABLE - LLM must not change this value.
    /// </summary>
    public required List<IncidentAlertRef> Alerts { get; init; }

    /// <summary>
    /// Metric snapshots correlated with this incident.
    /// Provides context for root cause analysis.
    /// IMMUTABLE - LLM must not change this value.
    /// </summary>
    public required List<IncidentMetricSnapshot> Metrics { get; init; }

    /// <summary>
    /// Recommendations for incident response.
    /// Generated by deterministic rules, optionally refined by LLM.
    /// MAY be enhanced by LLM with additional details/priorities.
    /// </summary>
    public required List<IncidentRecommendation> Recommendations { get; init; }

    /// <summary>
    /// When this incident was triaged.
    /// </summary>
    public required DateTime TriagedAt { get; init; }

    /// <summary>
    /// Optional trace ID for correlation with Phase 36 distributed traces.
    /// </summary>
    public string? CorrelatedTraceId { get; init; }

    /// <summary>
    /// Government compliance flag. Always true for TerraFusion incidents.
    /// Required for FISMA-High compliance.
    /// </summary>
    public bool Government { get; init; } = true;

    /// <summary>
    /// Indicates if LLM explanation service was used to enrich this summary.
    /// </summary>
    public bool LlmEnriched { get; init; } = false;

    /// <summary>
    /// Optional links to relevant Phase 37 Grafana dashboards.
    /// </summary>
    public List<string>? DashboardLinks { get; init; }

    /// <summary>
    /// Audit metadata for the triage process.
    /// </summary>
    public IncidentAuditInfo? AuditInfo { get; init; }
}

/// <summary>
/// Audit information for incident triage.
/// Required for government compliance and postmortem reviews.
/// </summary>
public record IncidentAuditInfo
{
    /// <summary>
    /// Version of the triage engine that classified this incident.
    /// </summary>
    public string? TriageEngineVersion { get; init; }

    /// <summary>
    /// Classification rules that contributed to the severity determination.
    /// </summary>
    public List<string>? AppliedRules { get; init; }

    /// <summary>
    /// Duration of the triage process in milliseconds.
    /// </summary>
    public long? TriageDurationMs { get; init; }

    /// <summary>
    /// If LLM was used, the model identifier.
    /// </summary>
    public string? LlmModelUsed { get; init; }

    /// <summary>
    /// Duration of LLM explanation in milliseconds (if used).
    /// </summary>
    public long? LlmExplanationDurationMs { get; init; }
}
