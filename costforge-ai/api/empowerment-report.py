    def test_all_endpoints(self) -> Dict[str, Any]:
        """Test all analytical endpoints to verify functionality"""
        logger.info("🧪 Testing all analytical endpoints...")

        test_results = {}
        base_url = "http://localhost:8001"

        endpoints = {
            "status": "/api/status",
            "market_drivers": "/api/market-drivers/demo-property?radius=2.0",
            "comparables": "/api/comparables/demo-property?radius=2.0",
            "trends": "/api/trends/demo-property",
            "valuation": "/api/valuation/demo-property",
            "comprehensive": "/api/comprehensive-analysis/demo-property"
        }

        for endpoint_name, endpoint_path in endpoints.items():
            try:
                response = requests.get(f"{base_url}{endpoint_path}", timeout=30)
                test_results[endpoint_name] = {
                    "status": "✅ OPERATIONAL" if response.status_code == 200 else f"❌ ERROR {response.status_code}",
                    "response_time": f"{response.elapsed.total_seconds() * 1000:.2f}ms",
                    "content_length": len(response.content) if response.content else 0
                }
                logger.info(f"✅ {endpoint_name}: {test_results[endpoint_name]['status']}")
            except Exception as e:
                test_results[endpoint_name] = {
                    "status": f"❌ CONNECTION ERROR",
                    "error": str(e),
                    "response_time": "N/A",
                    "content_length": 0
                }
                logger.error(f"❌ {endpoint_name}: Connection error - {str(e)}")

        return test_results

