#!/usr/bin/env python3
"""
Generate VS Code tasks.json from registry.yml

Usage: tf hub tasks
       python ops/tooling/generate-tasks.py

Output: .vscode/tasks.json (deterministic, regenerable)
"""

import yaml
import json
import hashlib
from pathlib import Path
from datetime import datetime

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "ops" / "tooling" / "registry.yml"
TASKS_FILE = ROOT / ".vscode" / "tasks.json"

# Magic header that verify-tasks.py checks for
GENERATED_MARKER = "AUTO-GENERATED by tf hub tasks — DO NOT EDIT"

def main():
    if not REGISTRY.exists():
        print(f"❌ Missing registry: {REGISTRY}")
        return 1
    
    with open(REGISTRY) as f:
        data = yaml.safe_load(f)
    
    tasks = []
    safe_count = 0
    risk_count = 0
    
    for group in data.get("groups", []):
        group_title = group.get("title", group["id"])
        # Clean emoji from group title for cleaner task names
        group_name = group_title.split(" ", 1)[-1] if group_title[0] in "🛡🚀🔮🧹📋" else group_title
        
        for item in group.get("items", []):
            safe = item.get("safe", True)
            
            # Skip meta commands
            if item["id"] in ("hub", "hub_list", "hub_find"):
                continue
            
            # Build label: "TF: Group → Command"
            label = f"TF: {group_name} → {item['title']}"
            if not safe:
                label = f"TF: ⚠️ {group_name} → {item['title']}"
                risk_count += 1
            else:
                safe_count += 1
            
            task = {
                "label": label,
                "type": "shell",
                "command": "${workspaceFolder}/ops/dev/tf.sh",
                "args": item["cmd"].replace("tf ", "").split(),
                "problemMatcher": [],
                "presentation": {
                    "reveal": "always",
                    "panel": "shared",
                    "clear": False,
                    "showReuseMessage": False
                },
                "group": {
                    "kind": "build" if safe else "none",
                    "isDefault": False
                },
                "detail": item.get("desc", "")
            }
            
            tasks.append(task)
    
    # Compute hash of registry for drift detection
    registry_hash = hashlib.sha256(REGISTRY.read_bytes()).hexdigest()[:12]
    
    # Write deterministic output with verification header
    TASKS_FILE.parent.mkdir(exist_ok=True)
    output = {
        "version": "2.0.0",
        "_generated": GENERATED_MARKER,
        "_registry_hash": registry_hash,
        "_generated_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "tasks": tasks
    }
    with open(TASKS_FILE, "w") as f:
        json.dump(output, f, indent=2)
    
    print(f"✓ Generated {len(tasks)} tasks → {TASKS_FILE.relative_to(ROOT)}")
    print(f"  {safe_count} safe (build group), {risk_count} risky (confirmation required)")
    print(f"  Use: Ctrl+Shift+P → Tasks: Run Task → TF:")
    return 0

if __name__ == "__main__":
    exit(main())

