#!/usr/bin/env python3
"""
Verify VS Code tasks.json matches registry.yml (drift detection)

Usage: tf hub verify
       python ops/tooling/verify-tasks.py

Checks:
  1. Generated marker header exists
  2. Registry hash matches current registry
  3. Task labels match expected from registry

Exit codes:
  0 = in sync
  1 = drift detected
  2 = missing files
"""

import yaml
import json
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "ops" / "tooling" / "registry.yml"
TASKS_FILE = ROOT / ".vscode" / "tasks.json"

GENERATED_MARKER = "AUTO-GENERATED by tf hub tasks — DO NOT EDIT"

def main():
    errors = []
    warnings = []
    
    # Check files exist
    if not REGISTRY.exists():
        print(f"❌ Missing registry: {REGISTRY}")
        return 2
    
    if not TASKS_FILE.exists():
        print(f"❌ Missing tasks.json: {TASKS_FILE}")
        print(f"   Run: tf hub tasks")
        return 2
    
    # Load tasks
    with open(TASKS_FILE) as f:
        tasks_data = json.load(f)
    
    # Check 1: Generated marker
    generated = tasks_data.get("_generated", "")
    if GENERATED_MARKER not in generated:
        errors.append("Missing or invalid _generated marker (file may have been hand-edited)")
    
    # Check 2: Registry hash
    current_hash = hashlib.sha256(REGISTRY.read_bytes()).hexdigest()[:12]
    stored_hash = tasks_data.get("_registry_hash", "")
    if stored_hash and stored_hash != current_hash:
        errors.append(f"Registry hash mismatch: tasks.json has {stored_hash}, registry is {current_hash}")
    elif not stored_hash:
        warnings.append("No registry hash in tasks.json (regenerate with tf hub tasks)")
    
    # Check 3: Task labels match
    with open(REGISTRY) as f:
        registry = yaml.safe_load(f)
    
    expected_labels = set()
    for group in registry.get("groups", []):
        group_title = group.get("title", group["id"])
        group_name = group_title.split(" ", 1)[-1] if group_title[0] in "🛡🚀🔮🧹📋" else group_title
        
        for item in group.get("items", []):
            if item["id"] in ("hub", "hub_list", "hub_find"):
                continue
            
            safe = item.get("safe", True)
            if safe:
                label = f"TF: {group_name} → {item['title']}"
            else:
                label = f"TF: ⚠️ {group_name} → {item['title']}"
            expected_labels.add(label)
    
    actual_labels = set()
    for task in tasks_data.get("tasks", []):
        label = task.get("label", "")
        if label.startswith("TF:"):
            actual_labels.add(label)
    
    missing = expected_labels - actual_labels
    extra = actual_labels - expected_labels
    
    if missing:
        errors.append(f"Missing {len(missing)} tasks from registry")
    if extra:
        errors.append(f"Extra {len(extra)} tasks not in registry")
    
    # Report results
    if errors:
        print(f"❌ Drift detected ({len(errors)} issues)")
        print("")
        for e in errors:
            print(f"  • {e}")
        if warnings:
            print("")
            for w in warnings:
                print(f"  ⚠ {w}")
        print("")
        print(f"  Fix: tf hub tasks")
        return 1
    
    if warnings:
        print(f"✓ tasks.json is in sync (with {len(warnings)} warnings)")
        for w in warnings:
            print(f"  ⚠ {w}")
    else:
        print(f"✓ tasks.json is in sync with registry.yml")
        print(f"  {len(actual_labels)} TF: tasks verified")
        print(f"  Registry hash: {current_hash}")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
