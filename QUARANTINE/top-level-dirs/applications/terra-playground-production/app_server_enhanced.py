class TerraFusionDeployer:
    """Handle deployment of generated applications"""
    
    @staticmethod
    def deploy_application(app_name, code, app_type, port):
        """Deploy application to the TerraFusion ecosystem"""
        try:
            # Create application directory
            app_dir = f"DEPLOYED_APPLICATIONS/{app_name}_PRODUCTION"
            os.makedirs(app_dir, exist_ok=True)
            
            # Determine file extension
            extensions = {
                'flask': 'py',
                'fastapi': 'py', 
                'express': 'js',
                'rust': 'rs'
            }
            ext = extensions.get(app_type, 'py')
            
            # Write application file
            app_file = os.path.join(app_dir, f"app.{ext}")
            with open(app_file, 'w') as f:
                f.write(code)
            
            # Create requirements.txt for Python apps
            if app_type in ['flask', 'fastapi']:
                requirements = """flask==2.3.3
flask-cors==4.0.0
sqlite3
"""
                with open(os.path.join(app_dir, 'requirements.txt'), 'w') as f:
                    f.write(requirements)
            
            # Create package.json for Node.js apps
            elif app_type == 'express':
                package_json = {
                    "name": app_name.lower(),
                    "version": "1.0.0",
                    "description": f"{app_name} - TerraFusion Application",
                    "main": "app.js",
                    "scripts": {
                        "start": "node app.js",
                        "dev": "nodemon app.js"
                    },
                    "dependencies": {
                        "express": "^4.18.2",
                        "sqlite3": "^5.1.6",
                        "cors": "^2.8.5"
                    }
                }
                with open(os.path.join(app_dir, 'package.json'), 'w') as f:
                    json.dump(package_json, f, indent=2)
            
            return {
                'success': True,
                'message': f'{app_name} deployed successfully',
                'path': app_dir,
                'port': port,
                'url': f'http://localhost:{port}'
            }
            
        except Exception as e:
            logger.error(f"Deployment error: {e}")
            return {
                'success': False,
                'message': f'Deployment failed: {str(e)}'
            }

