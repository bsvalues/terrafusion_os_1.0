    def update_package_json(self, workspace_path: Path, workspace_type: str) -> bool:
        """Update package.json with testing dependencies and scripts"""
        package_json_path = workspace_path / "package.json"
        
        if not package_json_path.exists():
            logger.warning(f"No package.json found in {workspace_path}")
            return False
        
        try:
            with open(package_json_path, 'r', encoding='utf-8') as f:
                package_data = json.load(f)
            
            # Add testing dependencies
            if "devDependencies" not in package_data:
                package_data["devDependencies"] = {}
            
            testing_deps = {
                "vitest": "^1.0.0",
                "jest": "^29.0.0",
                "@testing-library/react": "^13.0.0" if workspace_type in ["frontend", "marketplace"] else None,
                "@testing-library/jest-dom": "^6.0.0" if workspace_type in ["frontend", "marketplace"] else None,
                "@testing-library/user-event": "^14.0.0" if workspace_type in ["frontend", "marketplace"] else None,
                "@axe-core/react": "^4.0.0" if workspace_type in ["frontend", "marketplace"] else None,
                "ts-jest": "^29.0.0",
                "@types/jest": "^29.0.0",
                "jsdom": "^23.0.0" if workspace_type in ["frontend", "marketplace"] else None
            }
            
            # Filter out None values
            testing_deps = {k: v for k, v in testing_deps.items() if v is not None}
            
            package_data["devDependencies"].update(testing_deps)
            
            # Add testing scripts
            if "scripts" not in package_data:
                package_data["scripts"] = {}
            
            testing_scripts = {
                "test": "vitest",
                "test:watch": "vitest --watch",
                "test:coverage": "vitest --coverage",
                "test:ui": "vitest --ui",
                "test:government": "vitest --run --reporter=verbose",
                "test:accessibility": "vitest --run tests/accessibility",
                "test:performance": "vitest --run tests/performance"
            }
            
            package_data["scripts"].update(testing_scripts)
            
            # Write updated package.json
            with open(package_json_path, 'w', encoding='utf-8') as f:
                json.dump(package_data, f, indent=2)
            
            self.created_files.append(str(package_json_path))
            return True
            
        except Exception as e:
            logger.error(f"Failed to update package.json for {workspace_path}: {e}")
            return False
    
    def deploy_testing_framework(self) -> bool:
        """Deploy testing framework across all workspaces"""
        logger.info("🚀 Starting TerraFusion Testing Framework Deployment...")
        
        # Load workspace analysis
        analysis = self.load_workspace_analysis()
        workspace_details = analysis.get('workspace_details', {})
        
        # Get workspace categories
        categories = self.get_workspace_categories(workspace_details)
        
        total_workspaces = 0
        successful_deployments = 0
        
        for category, workspaces in categories.items():
            if not workspaces:
                continue
                
            logger.info(f"📊 Deploying testing framework for {category.upper()} workspaces...")
            
            for workspace_name in workspaces:
                total_workspaces += 1
                workspace_details_item = workspace_details.get(workspace_name, {})
                
                # Skip workspaces without package.json folders (likely not Node.js projects)
                package_json_folders = workspace_details_item.get('package_json_folders', [])
                if not package_json_folders and category in ['frontend', 'marketplace']:
                    logger.warning(f"Skipping {workspace_name} - no package.json folders")
                    continue
                
                logger.info(f"  🔧 Setting up testing for {workspace_name}...")
                
                # Determine workspace path
                if package_json_folders:
                    # Use the first package.json folder
                    relative_path = package_json_folders[0].lstrip("../")
                    workspace_path = self.root_path / relative_path
                else:
                    # For non-Node.js workspaces, use tests directory
                    workspace_path = self.root_path / "tests" / category / workspace_name
                
                success = True
                
                # Create testing configuration
                if category in ['frontend', 'marketplace']:
                    success &= self.create_vitest_config(workspace_path, category)
                    success &= self.create_jest_config(workspace_path, category)
                    success &= self.update_package_json(workspace_path, category)
                
                # Create test setup and samples for all workspaces
                success &= self.create_test_setup(workspace_path, category)
                success &= self.create_sample_tests(workspace_path, workspace_name, category)
                
                if success:
                    successful_deployments += 1
                    self.updated_workspaces.append(workspace_name)
                    logger.info(f"    ✅ Successfully configured testing for {workspace_name}")
                else:
                    logger.error(f"    ❌ Failed to configure testing for {workspace_name}")
        
        logger.info(f"🎊 Testing framework deployment complete!")
        logger.info(f"📊 Successfully configured: {successful_deployments}/{total_workspaces} workspaces")
        
        return successful_deployments > 0
    
    def generate_deployment_report(self) -> str:
        """Generate deployment report"""
