const gates = read(join(MEM, 'release-gates.md'));
const done = (gates.match(/- \[x\]/g) || []).length;
const open = (gates.match(/- \[ \]/g) || []).length;
const drift = read(join(MEM, 'drift-ledger.md'));
// severity from the Sev COLUMN, not a row-wide grep (finding text may contain "P0/P1")
const openSev = drift
  .split('\n')
  .filter(l => /^\|\s*D-\d+/.test(l) && /\|\s*Open\s*\|/i.test(l))
  .map(
    l =>
      l
        .split('|')
        .map(c => c.trim())
        .find(c => /^P[0-3]$/.test(c)) || 'P3'
  );
const p0 = openSev.filter(s => s === 'P0').length;
const p1 = openSev.filter(s => s === 'P1').length;
pages['release-1.0.md'] = page(
  { id: 'wiki.release', type: 'Release', status: 'active', release: release.name },
  `# ${release.name || 'TerraFusion OS 1.0'} — Release

- Branch: \`${release.branch || ''}\` · Active gate: ${release.active_gate || ''}
- Gates checked: **${done}/${done + open}** · Open drift: **P0=${p0}, P1=${p1}**
- Run \`brain release\` for the live confidence verdict.

## Must ship
${(release.must_ship || []).map(m => `- ${m}`).join('\n')}

## Explicitly deferred (post-1.0)
${(release.explicitly_deferred || []).map(d => `- ${d}`).join('\n')}`
);

pages['glossary.md'] = page(
  { id: 'wiki.glossary', type: 'Glossary', status: 'active' },
  `# Glossary

- **TerraTrace vs TerraAudit** — TerraTrace is the active append-only activity/evidence ledger (OS feature).
  "audit" is **reserved** for the future Auditor office; never use it for assessor activity. Use trace/compliance/activity.
- **Suite vs Module vs Feature** — Suite = a domain (Forge/Atlas/Dais/Dossier/GPT). Module = a unit inside a
  suite (\`terra-appeal\`). OS Feature = cross-cutting OS capability (TerraPilot, TerraTrace, Property Workbench) — not a suite.
- **Workbench vs App** — Property Workbench is a Tier-0 OS surface for parcel-scoped work. A Full Application
  is a tool hosted inside higher layers.
- **OS-owned vs Department-owned** — The OS Shell and Property Workbench are OS-owned (department-agnostic).
  Suites own their domain data per the [write-lane matrix](suite-boundaries.md).`
);

// per-suite pages (graph-native)
for (const [id, s] of Object.entries(canon.suites.active)) {
  const lane = canon.writeLanes.lanes[id] || { owns: [], must_not_write: [], bridge: '' };
  pages[`suites/${id}.md`] = page(
    {
      id: `suite.${id}`,
      type: 'Suite',
      status: 'active',
      owner: s.display,
      domain: s.domain,
      writes: s.owns,
      forbidden_writes: lane.must_not_write,
      verified_by: ['write-lanes', 'naming-lint'],
    },
    `# ${s.display}

**Domain:** ${s.domain}

## Owns (write lane)
${s.owns.map(w => `- ${w}`).join('\n')}

## Must not write
${(lane.must_not_write || []).map(w => `- ${w}`).join('\n') || '- —'}

## Cross-lane bridge
${lane.bridge || 'governed request + TerraTrace event'}`
  );
}

// ── write or check ──────────────────────────────────────────────────────────
const checkMode = process.argv.includes('--check');
let written = 0,
  stale = 0;
for (const [rel, content] of Object.entries(pages)) {
  const abs = join(WIKI, rel);
  if (checkMode) {
    const cur = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (cur !== content) {
      stale++;
      console.log(`stale: wiki/${rel}`);
    }
  } else {
    mkdirSync(join(abs, '..'), { recursive: true });
    writeFileSync(abs, content);
    written++;
  }
}

if (checkMode) {
  if (stale) {
    console.log(`\n❌ wiki is stale (${stale} page(s)) — run \`pnpm brain wiki\``);
    process.exit(1);
  }
  console.log(`✅ wiki current (${Object.keys(pages).length} pages match canon)`);
  process.exit(0);
}
console.log(
  `✅ Cortex Wiki published: ${written} pages → wiki/  (generated from canon — do not hand-edit)`
);
