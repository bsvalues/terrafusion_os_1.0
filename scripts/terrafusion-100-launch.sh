#!/usr/bin/env python3
"""
TerraFusion 100 Application Processing System
Real-time application management and scoring
"""

import datetime
import json
from dataclasses import dataclass
from typing import List, Dict, Optional

@dataclass
class CountyApplication:
    county_name: str
    state: str
    population: int
    annual_budget: int
    executive_contact: str
    tech_readiness_score: int  # 1-10 scale
    executive_endorsement: bool
    budget_authorization: bool
    implementation_team: int  # Number of team members
    federal_experience: bool
    application_timestamp: datetime.datetime
    
class TerraFusion100Processor:
    def __init__(self):
        self.applications = []
        self.founding_member_slots = 100
        self.application_deadline = datetime.datetime(2025, 8, 29, 14, 0)  # 2 PM EST
        
    def calculate_application_score(self, app: CountyApplication) -> float:
        """Calculate weighted application score for ranking"""
        score = 0.0
        
        # Population scoring (25% weight)
        if app.population >= 100_000:
            population_score = 100
        elif app.population >= 50_000:
            population_score = 80
        elif app.population >= 25_000:
            population_score = 60
        else:
            population_score = 40
        score += population_score * 0.25
        
        # Budget scoring (25% weight)  
        if app.annual_budget >= 50_000_000:
            budget_score = 100
        elif app.annual_budget >= 25_000_000:
            budget_score = 80
        elif app.annual_budget >= 10_000_000:
            budget_score = 60
        else:
            budget_score = 40
        score += budget_score * 0.25
        
        # Technical readiness (20% weight)
        score += app.tech_readiness_score * 10 * 0.20
        
        # Documentation completeness (15% weight)
        doc_score = 0
        if app.executive_endorsement:
            doc_score += 50
        if app.budget_authorization:
            doc_score += 50
        score += doc_score * 0.15
        
        # Implementation capacity (10% weight)
        if app.implementation_team >= 5:
            team_score = 100
        elif app.implementation_team >= 3:
            team_score = 80
        elif app.implementation_team >= 1:
            team_score = 60
        else:
            team_score = 20
        score += team_score * 0.10
        
        # Federal experience bonus (5% weight)
        federal_score = 100 if app.federal_experience else 0
        score += federal_score * 0.05
        
        return min(score, 100.0)  # Cap at 100
    
    def process_application(self, app_data: Dict) -> Dict:
        """Process incoming application and return status"""
        
        # Check if deadline passed
        if datetime.datetime.now() > self.application_deadline:
            return {
                'status': 'REJECTED',
                'reason': 'Application submitted after deadline',
                'timestamp': datetime.datetime.now().isoformat()
            }
        
        # Create application object
        application = CountyApplication(
            county_name=app_data['county_name'],
            state=app_data['state'],
            population=int(app_data['population']),
            annual_budget=int(app_data['annual_budget']),
            executive_contact=app_data['executive_contact'],
            tech_readiness_score=int(app_data['tech_readiness_score']),
            executive_endorsement=app_data.get('executive_endorsement', False),
            budget_authorization=app_data.get('budget_authorization', False),
            implementation_team=int(app_data.get('implementation_team', 0)),
            federal_experience=app_data.get('federal_experience', False),
            application_timestamp=datetime.datetime.now()
        )
        
        # Calculate application score
        score = self.calculate_application_score(application)
        
        # Store application
        self.applications.append({
            'application': application,
            'score': score,
            'processing_timestamp': datetime.datetime.now()
        })
        
        # Determine current ranking
        current_ranking = self.get_current_ranking()
        app_position = next((i for i, app in enumerate(current_ranking) 
                            if app['application'].county_name == application.county_name), None)
        
        if app_position is not None and app_position < self.founding_member_slots:
            status = 'QUALIFYING'
            founding_member = True
        else:
            status = 'WAITLIST'
            founding_member = False
            
        return {
            'status': status,
            'founding_member': founding_member,
            'score': score,
            'current_position': app_position + 1 if app_position is not None else len(current_ranking),
            'total_applications': len(self.applications),
            'slots_remaining': max(0, self.founding_member_slots - app_position - 1) if app_position is not None else 0,
            'timestamp': datetime.datetime.now().isoformat()
        }
    
    def get_current_ranking(self) -> List[Dict]:
        """Get current ranking of all applications"""
        return sorted(self.applications, key=lambda x: x['score'], reverse=True)
    
    def get_founding_members(self) -> List[Dict]:
        """Get final founding member selection"""
        ranking = self.get_current_ranking()
        return ranking[:self.founding_member_slots]
    
    def generate_selection_report(self) -> Dict:
        """Generate final selection report"""
        ranking = self.get_current_ranking()
        founding_members = self.get_founding_members()
        waitlist = ranking[self.founding_member_slots:]
        
        # Calculate statistics
        total_applications = len(self.applications)
        avg_population = sum(app['application'].population for app in self.applications) / total_applications
        avg_budget = sum(app['application'].annual_budget for app in self.applications) / total_applications
        avg_score = sum(app['score'] for app in self.applications) / total_applications
        
        # State distribution
        state_distribution = {}
        for app in self.applications:
            state = app['application'].state
            state_distribution[state] = state_distribution.get(state, 0) + 1
        
        # Selected states
        selected_states = {}
        for app in founding_members:
            state = app['application'].state
            selected_states[state] = selected_states.get(state, 0) + 1
        
        return {
            'selection_summary': {
                'total_applications': total_applications,
                'founding_members_selected': len(founding_members),
                'waitlist_size': len(waitlist),
                'selection_rate': len(founding_members) / total_applications * 100
            },
            'application_statistics': {
                'average_population': int(avg_population),
                'average_budget': int(avg_budget),
                'average_score': round(avg_score, 2),
                'state_distribution': state_distribution,
                'selected_state_distribution': selected_states
            },
            'founding_member_details': [
                {
                    'county': app['application'].county_name,
                    'state': app['application'].state,
                    'population': app['application'].population,
                    'budget': app['application'].annual_budget,
                    'score': app['score'],
                    'ranking': i + 1
                }
                for i, app in enumerate(founding_members)
            ],
            'program_value': {
                'total_counties_committed': len(founding_members),
                'annual_revenue_commitment': len(founding_members) * 250_000,
                'total_population_served': sum(app['application'].population for app in founding_members),
                'combined_county_budgets': sum(app['application'].annual_budget for app in founding_members)
            },
            'report_timestamp': datetime.datetime.now().isoformat()
        }

